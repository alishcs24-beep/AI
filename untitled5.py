import math

board = [" "] * 9
def show():
    print()
    print(board[0], "|", board[1], "|", board[2])
    print("--+---+--")
    print(board[3], "|", board[4], "|", board[5])
    print("--+---+--")
    print(board[6], "|", board[7], "|", board[8])
    print()

def winner(player):
    wins = [
        [0,1,2], [3,4,5], [6,7,8],
        [0,3,6], [1,4,7], [2,5,8],
        [0,4,8], [2,4,6]
    ]

    for w in wins:
        if board[w[0]] == player and \
           board[w[1]] == player and \
           board[w[2]] == player:
            return True

    return False

def draw():
    return " " not in board


def minimax(is_computer):

    if winner("X"):
        return 1

    if winner("O"):
        return -1

    if draw():
        return 0

    if is_computer:
        best = -math.inf

        for i in range(9):
            if board[i] == " ":
                board[i] = "X"

                score = minimax(False)

                board[i] = " "
                best = max(best, score)

        return best

    else:
        best = math.inf

        for i in range(9):
            if board[i] == " ":
                board[i] = "O"

                score = minimax(True)

                board[i] = " "
                best = min(best, score)

        return best


def computer_move():

    best_score = -math.inf
    best_move = 0

    for i in range(9):

        if board[i] == " ":

            board[i] = "X"

            score = minimax(False)

            board[i] = " "

            if score > best_score:
                best_score = score
                best_move = i

    board[best_move] = "X"

