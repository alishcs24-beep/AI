class VacuumEnvironment:
    def __init__(self):
        self.rooms = {
            "A": "Dirty",
            "B": "Dirty"
        }
        self.position = "A"

    def display(self):
        print(f"Room A: {self.rooms['A']}")
        print(f"Room B: {self.rooms['B']}")
        print(f"Vacuum position: {self.position}")



class SimpleReflexAgent:
    def act(self, location, status):
        if status == "Dirty":
            return "Suck"
        elif location == "A":
            return "Move Right"
        else:
            return "Move Left"


def run_simple_reflex():
    print("\n--- Simple Reflex Agent ---")

    env = VacuumEnvironment()
    agent = SimpleReflexAgent()

    for _ in range(6):
        env.display()

        status = env.rooms[env.position]
        action = agent.act(env.position, status)

        print("Action:", action)

        if action == "Suck":
            env.rooms[env.position] = "Clean"

        elif action == "Move Right":
            env.position = "B"

        elif action == "Move Left":
            env.position = "A"

        print()



class GoalBasedAgent:
    def __init__(self):
        self.goal = "Both rooms must be clean"

    def act(self, environment):
        # Goal: make every room clean
        if environment.rooms[environment.position] == "Dirty":
            return "Suck"

        if environment.rooms["A"] == "Dirty":
            return "Move Left"

        if environment.rooms["B"] == "Dirty":
            return "Move Right"

        return "Stop"


def run_goal_based():
    print("\n--- Goal-Based Agent ---")

    env = VacuumEnvironment()
    agent = GoalBasedAgent()

    while True:
        env.display()

        action = agent.act(env)
        print("Action:", action)

        if action == "Suck":
            env.rooms[env.position] = "Clean"

        elif action == "Move Right":
            env.position = "B"

        elif action == "Move Left":
            env.position = "A"

        elif action == "Stop":
            print("Goal achieved: Both rooms are clean.")
            break

        print()


run_simple_reflex()
